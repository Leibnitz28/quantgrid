@dataclass(frozen=True)
class CointegratedOU:
    """``ly = alpha_true + beta_true*lx + s`` where ``s`` is an OU process.

    ``half_life_s`` is the spread half-life in seconds (``theta = ln 2 / half_life_years``);
    ``sigma_s`` is the annualised spread volatility.
    """

    kind: ClassVar[str] = "cointegrated_ou"

    alpha_true: float
    beta_true: float
    half_life_s: int
    sigma_s: float

    def params(self) -> dict[str, Any]:
        return {
            "kind": self.kind,
            "alpha_true": self.alpha_true,
            "beta_true": self.beta_true,
            "half_life_s": self.half_life_s,
            "sigma_s": self.sigma_s,
        }


@dataclass(frozen=True)
class IndependentRandomWalk:
    """Negative control: ``log y`` is a random walk independent of ``x``."""

    kind: ClassVar[str] = "independent_rw"

    y_log_offset: float
    mu_y: float
    sigma_y: float

    def params(self) -> dict[str, Any]:
        return {
            "kind": self.kind,
            "y_log_offset": self.y_log_offset,
            "mu_y": self.mu_y,
            "sigma_y": self.sigma_y,
        }


@dataclass(frozen=True)
class DatasetDefinition:
    """One recorded synthetic dataset. All fields feed the generator and are reported in
    :attr:`DatasetInfo.generator`, except ``golden_sha256``, which pins the output."""

    name: str
    description: str
    seed: int
    n_grid: int
    start: datetime
    bar_interval_s: int
    mu_x: float
    sigma_x: float
    y_process: CointegratedOU | IndependentRandomWalk
    golden_sha256: str
    gap_fraction: float = 0.0
    price_decimals: int = PRICE_DECIMALS

    def __post_init__(self) -> None:
        if self.n_grid < 2:
            raise ValueError(f"{self.name}: n_grid must be >= 2")
        if self.bar_interval_s <= 0:
            raise ValueError(f"{self.name}: bar_interval_s must be > 0")
        if self.start.tzinfo is None or self.start.utcoffset() != timedelta(0):
            raise ValueError(f"{self.name}: start must be an aware UTC datetime")
        if not 0.0 <= self.gap_fraction < 1.0:
            raise ValueError(f"{self.name}: gap_fraction must be in [0, 1)")
        if self.seed < 0:
            raise ValueError(f"{self.name}: seed must be >= 0")
        if isinstance(self.y_process, CointegratedOU):
            if self.y_process.half_life_s <= 0:
                raise ValueError(f"{self.name}: half_life_s must be > 0")
            theta_dt = LN_2 / self.y_process.half_life_s * self.bar_interval_s
            if not 0.0 < theta_dt < 1.0:
                raise ValueError(f"{self.name}: theta*dt={theta_dt} must be in (0, 1)")

    @property
    def start_ns(self) -> int:
        delta = self.start - _EPOCH
        return (delta.days * 86_400 + delta.seconds) * _NS_PER_S + delta.microseconds * 1_000

    def generator_params(self) -> dict[str, Any]:
        """Every input of the generator (JSON-serialisable; reported in the catalog)."""
        return {
            "generator": GENERATOR_NAME,
            "generator_version": GENERATOR_VERSION,
            "seed": self.seed,
            "n_grid": self.n_grid,
            "start": self.start.isoformat().replace("+00:00", "Z"),
            "bar_interval_s": self.bar_interval_s,
            "x0": 100.0,
            "mu_x": self.mu_x,
            "sigma_x": self.sigma_x,
            **self.y_process.params(),
            "gap_fraction": self.gap_fraction,
            "gap_seed": self.seed + 1 if self.gap_fraction > 0.0 else None,
            "price_decimals": self.price_decimals,
        }

    def keep_mask(self) -> np.ndarray[Any, np.dtype[np.bool_]] | None:
        """Bars kept after deterministic gap removal (``None`` = no gaps)."""
        if self.gap_fraction <= 0.0:
            return None
        drop = np.random.default_rng(self.seed + 1).random(self.n_grid) < self.gap_fraction
        drop[0] = False
        drop[-1] = False
        return ~drop

    def timestamps(self) -> IntArray:
        """Observed bar timestamps (int64 ns UTC), after gap removal."""
        step = np.int64(self.bar_interval_s * _NS_PER_S)
        grid = np.int64(self.start_ns) + np.arange(self.n_grid, dtype=np.int64) * step
        keep = self.keep_mask()
        return grid if keep is None else grid[keep]

    def info(self) -> DatasetInfo:
        ts = self.timestamps()
        return DatasetInfo(
            name=self.name,
            sha256=self.golden_sha256,
            n_bars=int(ts.shape[0]),
            start=ns_to_datetime(int(ts[0])),
            end=ns_to_datetime(int(ts[-1])),
            bar_interval_s=self.bar_interval_s,
            columns=BAR_COLUMNS,
            synthetic=True,
            license=DATASET_LICENSE,
            description=self.description,
            generator=self.generator_params(),
        )

    def ref(self) -> DatasetRef:
        return DatasetRef(name=self.name, sha256=self.golden_sha256)


def _utc(text: str) -> datetime:
    return datetime.fromisoformat(text).astimezone(UTC)


