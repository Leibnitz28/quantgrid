def _random_walk(level0: float, drift: float, vol: float, shocks: FloatArray) -> FloatArray:
    """``l[0] = level0``, ``l[t] = l[t-1] + (drift + vol*shocks[t])`` (sequential sums)."""
    increments = drift + vol * shocks
    increments[0] = level0
    # numpy's add.accumulate is a strictly sequential left-to-right loop (no pairwise
    # reassociation), so this equals the explicit recursion bit for bit.
    return np.cumsum(increments)


def _ou_path(theta: float, dt: float, vol: float, shocks: FloatArray) -> FloatArray:
    """``s[0] = 0``, ``s[t] = s[t-1] - theta*s[t-1]*dt + vol*shocks[t]`` (exact op order)."""
    scaled = (vol * shocks).tolist()
    out = [0.0] * len(scaled)
    s = 0.0
    for t in range(1, len(scaled)):
        s = s - theta * s * dt + scaled[t]
        out[t] = s
    return np.array(out, dtype=np.float64)


def _quantised_exp(log_prices: FloatArray, decimals: int) -> FloatArray:
    values = np.fromiter(
        map(math.exp, log_prices.tolist()), dtype=np.float64, count=log_prices.shape[0]
    )
    return np.round(values, decimals)


def generate_arrays(defn: DatasetDefinition) -> tuple[IntArray, FloatArray, FloatArray]:
    """Run the deterministic generator (see module docstring). Pure function of ``defn``."""
    n = defn.n_grid
    dt = defn.bar_interval_s / SECONDS_PER_YEAR
    sqrt_dt = math.sqrt(dt)
    rng = np.random.default_rng(defn.seed)
    e_x = rng.standard_normal(n)
    e_2 = rng.standard_normal(n)
    lx = _random_walk(LN_100, defn.mu_x * dt, defn.sigma_x * sqrt_dt, e_x)
    proc = defn.y_process
    if isinstance(proc, CointegratedOU):
        theta = LN_2 / (proc.half_life_s / SECONDS_PER_YEAR)
        spread = _ou_path(theta, dt, proc.sigma_s * sqrt_dt, e_2)
        ly = proc.alpha_true + proc.beta_true * lx + spread
    else:
        ly = _random_walk(LN_100 + proc.y_log_offset, proc.mu_y * dt, proc.sigma_y * sqrt_dt, e_2)
    close_x = _quantised_exp(lx, defn.price_decimals)
    close_y = _quantised_exp(ly, defn.price_decimals)
    ts = defn.timestamps()
    keep = defn.keep_mask()
    if keep is not None:
        close_x = close_x[keep]
        close_y = close_y[keep]
    return ts, close_x, close_y


def generate_bars(name: str, *, verify: bool = True) -> Bars:
    """Generate a registered dataset in memory (no files).

    With ``verify`` (default) the logical hash must equal the recorded golden signature,
    else :class:`DataIntegrityError`. The returned arrays are read-only.
    """
    defn = get_definition(name)
    ts, close_x, close_y = generate_arrays(defn)
    validate_bars(ts, close_x, close_y)
    sha = dataset_content_sha256(ts, close_x, close_y)
    if verify and sha != defn.golden_sha256:
        raise DataIntegrityError(
            f"generator output for {name!r} does not match its recorded signature "
            f"(generated {sha}, recorded {defn.golden_sha256})",
            details={"dataset": name, "generated": sha, "recorded": defn.golden_sha256},
        )
    return _make_bars(name, ts, close_x, close_y, sha)


def _make_bars(name: str, ts: IntArray, close_x: FloatArray, close_y: FloatArray, sha: str) -> Bars:
    for arr in (ts, close_x, close_y):
        arr.setflags(write=False)
    return Bars(name=name, ts=ts, close_x=close_x, close_y=close_y, sha256=sha)


