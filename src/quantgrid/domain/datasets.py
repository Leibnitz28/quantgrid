def dataset_path(name: str, data_dir: Path) -> Path:
    return Path(data_dir) / "datasets" / f"{name}.parquet"


_MATERIALIZE_LOCKS: dict[str, threading.Lock] = {}
_MATERIALIZE_LOCKS_GUARD = threading.Lock()


def _materialize_lock(name: str) -> threading.Lock:
    with _MATERIALIZE_LOCKS_GUARD:
        return _MATERIALIZE_LOCKS.setdefault(name, threading.Lock())


def _fsync_dir(directory: Path) -> None:
    if os.name != "posix":  # pragma: no cover - directory fsync is POSIX-only
        return
    fd = os.open(directory, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def _write_parquet_atomic(
    path: Path, ts: IntArray, close_x: FloatArray, close_y: FloatArray, metadata: dict[bytes, bytes]
) -> None:
    """Write via temp file in the same directory, fsync, ``os.replace``, fsync directory."""
    import pyarrow as pa
    import pyarrow.parquet as pq

    table = pa.table(
        {
            "ts": pa.array(ts, type=pa.timestamp("ns", tz="UTC")),
            "close_x": pa.array(close_x, type=pa.float64()),
            "close_y": pa.array(close_y, type=pa.float64()),
        }
    ).replace_schema_metadata(metadata)
    directory = path.parent
    directory.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=directory)
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "wb") as fh:
            pq.write_table(table, fh, compression="zstd")
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except BaseException:
        tmp.unlink(missing_ok=True)
        raise
    _fsync_dir(directory)


def _expected_schema() -> Any:
    import pyarrow as pa

    return pa.schema(
        [
            ("ts", pa.timestamp("ns", tz="UTC")),
            ("close_x", pa.float64()),
            ("close_y", pa.float64()),
        ]
    )


def _read_parquet(path: Path) -> tuple[IntArray, FloatArray, FloatArray, dict[bytes, bytes]]:
    """Read and structurally check a bars file (any failure -> DataIntegrityError)."""
    import pyarrow as pa
    import pyarrow.parquet as pq

    try:
        table = pq.read_table(path)
    except (OSError, ValueError, pa.ArrowException) as exc:
        raise DataIntegrityError(f"cannot read dataset file {path}: {exc}") from exc
    metadata = dict(table.schema.metadata or {})
    if not table.schema.remove_metadata().equals(_expected_schema()):
        raise DataIntegrityError(
            f"dataset file {path} has an unexpected schema: {table.schema.remove_metadata()}"
        )
    for name in BAR_COLUMNS:
        if table.column(name).null_count:
            raise DataIntegrityError(f"dataset file {path}: column {name!r} contains nulls")
    try:
        ts = np.ascontiguousarray(table.column("ts").cast(pa.int64()).to_numpy(), dtype=np.int64)
        close_x = np.ascontiguousarray(table.column("close_x").to_numpy(), dtype=np.float64)
        close_y = np.ascontiguousarray(table.column("close_y").to_numpy(), dtype=np.float64)
    except (ValueError, pa.ArrowException) as exc:  # pragma: no cover - defensive
        raise DataIntegrityError(f"cannot decode dataset file {path}: {exc}") from exc
    return ts, close_x, close_y, metadata


def _verified_bars(path: Path, defn: DatasetDefinition, *, verify: bool) -> Bars:
    ts, close_x, close_y, metadata = _read_parquet(path)
    validate_bars(ts, close_x, close_y)
    recorded_meta = metadata.get(META_SHA256)
    if recorded_meta is not None and recorded_meta.decode("ascii", "replace") != defn.golden_sha256:
        raise DataIntegrityError(
            f"dataset file {path} declares signature {recorded_meta!r}, registry records "
            f"{defn.golden_sha256}"
        )
    if verify:
        sha = dataset_content_sha256(ts, close_x, close_y)
        if sha != defn.golden_sha256:
            raise DataIntegrityError(
                f"checksum mismatch for {defn.name!r}: file content hashes to {sha}, registry "
                f"records {defn.golden_sha256}",
                details={"dataset": defn.name, "actual": sha, "expected": defn.golden_sha256},
            )
    else:
        sha = defn.golden_sha256  # trusted, not recomputed (strict_dataset_check disabled)
    return _make_bars(defn.name, ts, close_x, close_y, sha)


def materialize(name: str, data_dir: Path) -> Path:
    """Ensure ``data_dir/datasets/<name>.parquet`` exists and holds the recorded bars.

    Idempotent: a valid existing file is verified (logical hash) and left untouched. A
    missing or invalid file is (re)generated, its logical hash checked against the golden
    signature *before* anything is written, then published atomically (temp file in the
    same directory, flush + fsync, ``os.replace``, directory fsync). Concurrent writers are
    safe: each writes its own temp file and the replace is atomic.
    """
    defn = get_definition(name)
    path = dataset_path(name, data_dir)
    with _materialize_lock(name):
        if path.exists():
            try:
                _verified_bars(path, defn, verify=True)
                return path
            except DataIntegrityError as exc:
                logger.warning(
                    "dataset file failed verification; regenerating",
                    extra={"dataset": name, "path": str(path), "error": exc.message},
                )
        ts, close_x, close_y = generate_arrays(defn)
        validate_bars(ts, close_x, close_y)
        sha = dataset_content_sha256(ts, close_x, close_y)
        if sha != defn.golden_sha256:
            raise DataIntegrityError(
                f"refusing to materialise {name!r}: generated signature {sha} differs from the "
                f"recorded {defn.golden_sha256} (generator or platform drift)",
                details={"dataset": name, "generated": sha, "recorded": defn.golden_sha256},
            )
        metadata = {
            META_SHA256: sha.encode("ascii"),
            META_GENERATOR: canonical_json(defn.generator_params()).encode("ascii"),
            META_NAME: name.encode("ascii"),
        }
        _write_parquet_atomic(path, ts, close_x, close_y, metadata)
        logger.info("dataset materialised", extra={"dataset": name, "path": str(path)})
        return path


def load_bars(
    ref: DatasetRef, data_dir: Path, *, auto_materialize: bool, verify: bool = True
) -> Bars:
    """Load recorded bars for ``ref`` and prove they are the recorded content.

    Raises :class:`DataIntegrityError` (non-retryable) when the dataset is unknown,
    ``ref.sha256`` differs from the registry's golden signature, the file is missing and
    ``auto_materialize`` is false, the file is unreadable or has the wrong schema, the bars
    fail :func:`validate_bars`, or (with ``verify``) the recomputed logical hash differs
    from the golden signature. Returned arrays are read-only, so cached bars can be shared.
    """
    defn = get_definition(ref.name)
    if ref.sha256 != defn.golden_sha256:
        raise DataIntegrityError(
            f"dataset {ref.name!r}: requested signature {ref.sha256} differs from the recorded "
            f"{defn.golden_sha256}",
            details={"dataset": ref.name, "requested": ref.sha256, "recorded": defn.golden_sha256},
        )
    path = dataset_path(ref.name, data_dir)
    if not path.exists():
        if not auto_materialize:
            raise DataIntegrityError(
                f"dataset file {path} is missing and auto-materialisation is disabled",
                details={"dataset": ref.name, "path": str(path)},
            )
        materialize(ref.name, data_dir)
    return _verified_bars(path, defn, verify=verify)


class BarsCache:
    """Thread-safe in-process LRU of loaded :class:`Bars`, keyed by logical SHA-256.

    Workers run many tasks on the same few datasets, so this avoids re-reading and
    re-hashing. Loads of the same key are single-flight (one thread loads, the others
    wait). Cached arrays are read-only. A hit whose cached name differs from the requested
    name is treated as a miss, so :func:`load_bars` still rejects a mismatched ref.
    """

    def __init__(self, capacity: int = 4) -> None:
        if capacity < 1:
            raise ValueError("capacity must be >= 1")
        self.capacity = capacity
        self._entries: OrderedDict[str, Bars] = OrderedDict()
        self._lock = threading.Lock()
        self._key_locks: dict[str, threading.Lock] = {}
        self.hits = 0
        self.misses = 0
        self.evictions = 0

    def __len__(self) -> int:
        with self._lock:
            return len(self._entries)

    def get(self, sha256: str) -> Bars | None:
        with self._lock:
            bars = self._entries.get(sha256)
            if bars is not None:
                self._entries.move_to_end(sha256)
            return bars

    def put(self, bars: Bars) -> None:
        with self._lock:
            self._entries[bars.sha256] = bars
            self._entries.move_to_end(bars.sha256)
            while len(self._entries) > self.capacity:
                self._entries.popitem(last=False)
                self.evictions += 1

    def clear(self) -> None:
        with self._lock:
            self._entries.clear()

    def stats(self) -> dict[str, int]:
        with self._lock:
            return {
                "size": len(self._entries),
                "capacity": self.capacity,
                "hits": self.hits,
                "misses": self.misses,
                "evictions": self.evictions,
            }

    def _lookup(self, ref: DatasetRef) -> Bars | None:
        with self._lock:
            bars = self._entries.get(ref.sha256)
            if bars is not None and bars.name == ref.name:
                self._entries.move_to_end(ref.sha256)
                self.hits += 1
                return bars
            return None

    def get_or_load(
        self, ref: DatasetRef, data_dir: Path, *, auto_materialize: bool, verify: bool = True
    ) -> Bars:
        bars = self._lookup(ref)
        if bars is not None:
            return bars
        with self._lock:
            key_lock = self._key_locks.setdefault(ref.sha256, threading.Lock())
        with key_lock:
            bars = self._lookup(ref)  # another thread may have loaded it meanwhile
            if bars is not None:
                return bars
            with self._lock:
                self.misses += 1
            bars = load_bars(ref, data_dir, auto_materialize=auto_materialize, verify=verify)
            self.put(bars)
            return bars
